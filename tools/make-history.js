// Builds games/price-history.js: real US average prices (BLS "Average Price Data", CPI program) by year.
// Usage: node tools/make-history.js     (5 requests to the free BLS API v1)
const fs = require('fs'), path = require('path');
const SERIES = {
  APU0000708111:['Eggs','1 dozen, grade A large','🥚'], APU0000709112:['Whole milk','1 gallon','🥛'], APU0000702111:['White bread','1 lb loaf','🍞'],
  APU0000703112:['Ground beef','1 lb','🥩'], APU0000717311:['Ground coffee','1 lb','☕'], APU0000715211:['White sugar','1 lb','🍬'],
  APU0000711211:['Bananas','1 lb','🍌'], APU000074714:['Regular gasoline','1 gallon','⛽'], APU0000706111:['Whole chicken','1 lb','🍗'],
  APU0000711311:['Navel oranges','1 lb','🍊'], APU0000712112:['White potatoes','1 lb','🥔'], APU0000712311:['Tomatoes','1 lb','🍅'],
  APU0000701312:['Long-grain white rice','1 lb, uncooked','🍚'], APU0000701111:['All-purpose flour','1 lb','🌾'], APU0000704111:['Sliced bacon','1 lb','🥓'],
  APU0000713111:['Frozen orange juice','12 oz can','🧃'], APU0000710212:['Cheddar cheese','1 lb','🧀'], APU0000710411:['Ice cream','½ gallon','🍦'],
  APU0000711111:['Red Delicious apples','1 lb','🍎'], APU0000712211:['Iceberg lettuce','1 lb','🥬'], APU0000FF1101:['Boneless chicken breast','1 lb','🍗'],
  APU0000FS1101:['Butter','1 lb','🧈'], APU000072610:['Electricity','1 kilowatt-hour','💡'], APU0000714233:['Cola','2 liters','🥤'],
};
(async () => {
  const out = {};
  for (const [a, b] of [[1980, 1989], [1990, 1999], [2000, 2009], [2010, 2019], [2020, 2029]]) {
    const r = await (await fetch('https://api.bls.gov/publicAPI/v1/timeseries/data/', { method:'POST', headers:{ 'Content-Type':'application/json' },
      body:JSON.stringify({ seriesid:Object.keys(SERIES), startyear:String(a), endyear:String(Math.min(b, new Date().getFullYear())) }) })).json();
    if (r.status !== 'REQUEST_SUCCEEDED') throw new Error(JSON.stringify(r.message));
    r.Results.series.forEach(s => s.data.forEach(d => {
      if (!/^M(0[1-9]|1[0-2])$/.test(d.period) || d.value === '-') return;
      const y = +d.year, v = +d.value; ((out[s.seriesID] = out[s.seriesID] || {})[y] = out[s.seriesID][y] || []).push(v);
    }));
  }
  // annual average of the months available
  const rows = [];
  Object.entries(out).forEach(([id, years]) => {
    const [name, unit, icon] = SERIES[id];
    Object.entries(years).forEach(([y, vs]) => { if (vs.length >= 6) rows.push([name, unit, icon, +y, Math.round(vs.reduce((s, x) => s + x, 0) / vs.length * 100) / 100]); });
  });
  fs.writeFileSync(path.join(__dirname, '..', 'games', 'price-history.js'),
`/* Real US average prices by year (U.S. Bureau of Labor Statistics, CPI Average Price Data, annual average of monthly prices).
   Row: [item, size, icon, year, price]. Generated by tools/make-history.js on ${new Date().toISOString().slice(0, 10)}. */
window.PRICE_HISTORY = ${JSON.stringify(rows)};
`);
  const ys = rows.map(r => r[3]);
  console.log('rows', rows.length, 'items', new Set(rows.map(r => r[0])).size, 'years', Math.min(...ys), '-', Math.max(...ys));
})();
